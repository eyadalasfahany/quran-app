<?php

declare(strict_types=1);

namespace App\Domains\Azkar\Console;

use App\Domains\Azkar\Exceptions\CatalogueUnreadableException;
use App\Domains\Azkar\Exceptions\SnapshotException;
use App\Domains\Azkar\OpenDua\CatalogueDownloader;
use App\Domains\Azkar\Services\HadeethEncLinker;
use App\Domains\Azkar\Sources\AzkarSourceRegistry;
use App\Domains\Azkar\Sources\HadeethEncSnapshot;
use App\Support\Storage\SourceCache;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

/**
 * Writes config/azkar_hadeethenc_links.php: candidate links between primary entries and HadeethEnc hadiths (ADR 0031
 * §12). The file holds keys, hadith ids and evidence only, never text. Reviewed links are kept as they are.
 */
final class HadeethEncLinksCommand extends Command
{
    use ResolvesCataloguePath;

    protected $signature = 'azkar:hadeethenc-links
        {path? : The OpenDua catalogue file (omit with --download)}
        {--download : Download the pinned OpenDua catalogue first}';

    protected $description = 'Write candidate links between Azkar entries and HadeethEnc hadiths, ids and evidence only (ADR 0031 §12).';

    public function handle(CatalogueDownloader $downloader, AzkarSourceRegistry $sources, HadeethEncSnapshot $snapshot, HadeethEncLinker $linker): int
    {
        $path = $this->resolveCataloguePath($downloader);

        if ($path === null) {
            return self::FAILURE;
        }

        try {
            $catalogue = $sources->for('opendua')->parse($path);
            $records = $snapshot->load(SourceCache::path('azkar/hadeethenc/'.(string) config('azkar.hadeethenc.snapshot_date')));
        } catch (CatalogueUnreadableException|SnapshotException $exception) {
            $this->error($exception->getMessage());

            return self::FAILURE;
        }

        $output = config_path('azkar_hadeethenc_links.php');
        $existing = is_file($output) ? (array) require $output : [];
        $result = $linker->build($catalogue->data, $records, $existing);

        File::put($output, $this->render($result['rows']));

        $this->table(['Metric', 'Value'], [
            ['hadiths in snapshot', count($records)],
            ['entries checked', $result['stats']['entries_checked']],
            ['entries with a candidate link', $result['stats']['entries_linked']],
            ['links written', $result['stats']['links']],
            ['reviewed links kept', $result['stats']['reviewed_kept']],
            ['minimum match (normalised characters)', (int) config('azkar.hadeethenc.min_match_chars', 40)],
        ]);
        $this->line('Links written to: '.$output.' (ids and evidence only)');

        return self::SUCCESS;
    }

    private function quote(string $value): string
    {
        return "'".addcslashes($value, "'\\")."'";
    }

    /**
     * @param  array<string, list<array<string, int|string>>>  $rows
     */
    private function render(array $rows): string
    {
        $lines = [
            '<?php',
            '',
            'declare(strict_types=1);',
            '',
            '/*',
            '|--------------------------------------------------------------------------',
            '| HadeethEnc links (ADR 0031 §12)',
            '|--------------------------------------------------------------------------',
            '|',
            '| Generated by `php artisan azkar:hadeethenc-links`. Ids and evidence only: no hadith text, no dhikr text.',
            '| Each row: entry_key => [hadeeth_id, status (candidate|reviewed), evidence (contains:<normalised chars>)].',
            '| Production uses reviewed links only. Re-running the command keeps every reviewed link.',
            '*/',
            '',
            'return [',
        ];

        foreach ($rows as $entryKey => $links) {
            $lines[] = '    '.$this->quote((string) $entryKey).' => [';

            foreach ($links as $link) {
                $lines[] = sprintf(
                    "        ['hadeeth_id' => %d, 'status' => %s, 'evidence' => %s],",
                    (int) $link['hadeeth_id'],
                    $this->quote((string) $link['status']),
                    $this->quote((string) $link['evidence']),
                );
            }

            $lines[] = '    ],';
        }

        $lines[] = '];';

        return implode("\n", $lines)."\n";
    }
}
