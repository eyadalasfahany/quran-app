<?php

declare(strict_types=1);

namespace App\Domains\Azkar\Services;

use Illuminate\Support\Facades\File;

/**
 * Renders the Quran reference map as config/azkar_quran_map.php. The file holds keys, references and status only.
 * Never Quran or dhikr text (ADR 0031 §4, §11).
 */
final class QuranReferenceMapWriter
{
    /**
     * @param  array<string, list<array<array-key, mixed>>>  $rows
     */
    public function write(string $path, array $rows): void
    {
        File::put($path, $this->render($rows));
    }

    /**
     * @param  array<string, list<array<array-key, mixed>>>  $rows
     */
    public function render(array $rows): string
    {
        $lines = [
            '<?php',
            '',
            'declare(strict_types=1);',
            '',
            '/*',
            '|--------------------------------------------------------------------------',
            '| Quran reference map (ADR 0031 §4, §11)',
            '|--------------------------------------------------------------------------',
            '|',
            '| Generated by `php artisan azkar:quran-map-candidates`. References and match evidence only: no Quran text',
            '| and no dhikr text. One row per Quran span, in span order:',
            '|   [surah, verse_from, verse_to|null, \'status\' => ..., \'evidence\' => ..., \'check\' => ..., \'ranges\' => ...]',
            '| `ranges` appears only for a span that runs across surah boundaries and lists every range in order.',
            '|',
            '| status: candidate (a match to review), unmatched (no confident match; blocks the entry),',
            '| reviewed (checked by the developer). Production imports accept only reviewed rows. Re-running the',
            '| command keeps every reviewed row.',
            '*/',
            '',
            'return [',
        ];

        foreach ($rows as $itemKey => $spans) {
            $lines[] = '    '.$this->scalar($itemKey).' => [';

            foreach ($spans as $span) {
                $lines[] = '        '.$this->row($span).',';
            }

            $lines[] = '    ],';
        }

        $lines[] = '];';

        return implode("\n", $lines)."\n";
    }

    /**
     * @param  array<array-key, mixed>  $span
     */
    private function row(array $span): string
    {
        $parts = [
            $this->scalar($span[0] ?? null),
            $this->scalar($span[1] ?? null),
            $this->scalar($span[2] ?? null),
            "'status' => ".$this->scalar($span['status'] ?? null),
            "'evidence' => ".$this->scalar($span['evidence'] ?? null),
        ];

        if (array_key_exists('check', $span)) {
            $parts[] = "'check' => ".$this->scalar($span['check']);
        }

        if (is_array($span['ranges'] ?? null)) {
            $ranges = array_map(
                fn (array $range): string => '['.implode(', ', array_map(fn (mixed $value): string => $this->scalar($value), $range)).']',
                $span['ranges'],
            );
            $parts[] = "'ranges' => [".implode(', ', $ranges).']';
        }

        return '['.implode(', ', $parts).']';
    }

    private function scalar(mixed $value): string
    {
        return match (true) {
            $value === null => 'null',
            is_int($value) => (string) $value,
            is_string($value) => "'".addcslashes($value, "'\\")."'",
            default => throw new \UnexpectedValueException('The map holds only strings, integers and null.'),
        };
    }
}
