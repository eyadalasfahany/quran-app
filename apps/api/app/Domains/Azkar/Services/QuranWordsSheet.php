<?php

declare(strict_types=1);

namespace App\Domains\Azkar\Services;

use App\Domains\Azkar\Exceptions\QuranMapException;
use App\Support\QuranText\QuranWordMap;

/**
 * Renders docs/plans/partial-verse-segments/words.md (ADR 0093): for every span that is a partial-verse range or is
 * still unmatched, its key, its status and evidence, and the verses with their word counts and quoted positions.
 *
 * The sheet holds keys, verse references and word positions only, never Quran or dhikr text. The developer checks the
 * positions against the Tanzil text in the reader, and marks the row reviewed in config/azkar_quran_map.php.
 */
final class QuranWordsSheet
{
    public function __construct(
        private readonly QuranWordMap $words,
    ) {}

    /**
     * @param  array<string, list<array<array-key, mixed>>>  $rows  The map rows, keyed by item key.
     */
    public function render(array $rows): string
    {
        $lines = [
            '# Partial-verse segments: word positions for review',
            '',
            'Generated by `php artisan azkar:quran-map-candidates --words-sheet` (ADR 0093, plan `docs/plans/partial-verse-segments.md`).',
            'Keys, verse references and word positions only: no Quran or dhikr text. Compare the positions with the Tanzil',
            'text in the reader. Only the developer marks a row `reviewed`.',
            '',
        ];

        $sections = 0;

        foreach ($rows as $itemKey => $spans) {
            foreach ($spans as $index => $span) {
                if (! $this->listed($span)) {
                    continue;
                }

                $sections++;
                $lines[] = sprintf('## %s, span %d', $itemKey, $index + 1);
                $lines[] = '';
                $lines[] = sprintf('- Status: %s', (string) ($span['status'] ?? 'none'));
                $lines[] = sprintf('- Evidence: %s', (string) ($span['evidence'] ?? 'none'));

                if (is_array($span['words'] ?? null)) {
                    $lines = [...$lines, ...$this->wordLines($span)];
                } else {
                    $lines[] = '- Range: no word range (matcher reference '.$this->reference($span).')';
                }

                $lines[] = ($span['status'] ?? null) === QuranReferencePolicy::REVIEWED
                    ? sprintf('- Decision: reviewed by the developer (%s)', (string) ($span['evidence'] ?? 'none'))
                    : '- Decision: [ ] reviewed (range as shown)  [ ] stays excluded';
                $lines[] = '';
            }
        }

        if ($sections === 0) {
            $lines[] = 'No span is listed.';
        }

        return implode("\n", $lines)."\n";
    }

    /**
     * @param  array<array-key, mixed>  $span
     */
    private function listed(array $span): bool
    {
        return is_array($span['words'] ?? null) || ($span['status'] ?? null) === QuranReferencePolicy::UNMATCHED;
    }

    /**
     * @param  array<array-key, mixed>  $span
     * @return list<string>
     */
    private function wordLines(array $span): array
    {
        $surah = (int) ($span[0] ?? 0);
        $from = (int) ($span[1] ?? 0);
        $to = is_int($span[2] ?? null) ? $span[2] : $from;
        [$wordFrom, $wordTo] = $span['words'];
        $lines = [];

        for ($ayah = $from; $ayah <= $to; $ayah++) {
            $count = $this->words->wordCount($surah, $ayah);

            if ($count === null) {
                throw new QuranMapException(sprintf('Verse %d:%d is not in the Quran word map.', $surah, $ayah));
            }

            $first = $ayah === $from && is_int($wordFrom) ? $wordFrom : 1;
            $last = $ayah === $to && is_int($wordTo) ? $wordTo : $count;
            $lines[] = sprintf(
                '- Verse %d:%d: %d words; quoted positions %d to %d (%d words)',
                $surah,
                $ayah,
                $count,
                $first,
                $last,
                $last - $first + 1,
            );
        }

        return $lines;
    }

    /**
     * @param  array<array-key, mixed>  $span
     */
    private function reference(array $span): string
    {
        if (! is_int($span[0] ?? null) || ! is_int($span[1] ?? null)) {
            return 'none';
        }

        return is_int($span[2] ?? null)
            ? sprintf('%d:%d-%d', $span[0], $span[1], $span[2])
            : sprintf('%d:%d', $span[0], $span[1]);
    }
}
