<?php

declare(strict_types=1);

namespace App\Domains\Duas\Services;

use Illuminate\Support\Facades\File;

/**
 * Renders the Duas Quran reference map as config/duas_quran_map.php. The file holds verse
 * keys, references and status only. Never Quran text (ADR 0044-duas §2, non-negotiable 1).
 */
final class QuranDuaMapWriter
{
    /**
     * @param  array<string, list<array<array-key, mixed>>>  $rows
     */
    public function write(string $path, array $rows): void
    {
        File::put($path, $this->render($rows));
    }

    /**
     * @param  array<string, list<array<array-key, mixed>>>  $rows
     */
    public function render(array $rows): string
    {
        $lines = [
            '<?php',
            '',
            'declare(strict_types=1);',
            '',
            '/*',
            '|--------------------------------------------------------------------------',
            '| Quranic duas: Quran reference map (ADR 0044-duas §2)',
            '|--------------------------------------------------------------------------',
            '|',
            '| Generated by `php artisan duas:quran-candidates`. Verse references and matching rule only: no Quran text.',
            '| One row per candidate verse:',
            '|   [surah, verse_from, verse_to|null, \'status\' => ..., \'rule\' => ...]',
            '|',
            '| status: candidate (awaiting review), reviewed (checked by the developer), rejected, or added (by reviewer)',
            '| rule: rule_vocative_rabb, rule_speech_verb, rule_contains_allahumma, rule_imperative_list',
            '|',
            '| Production accepts only reviewed and added rows. Re-running the command preserves',
            '| reviewed, rejected and added rows exactly as they are.',
            '*/',
            '',
            'return [',
        ];

        foreach ($rows as $key => $spans) {
            $lines[] = '    '.$this->scalar($key).' => [';

            foreach ($spans as $span) {
                $lines[] = '        '.$this->row($span).',';
            }

            $lines[] = '    ],';
        }

        $lines[] = '];';

        return implode("\n", $lines)."\n";
    }

    /**
     * @param  array<array-key, mixed>  $span
     */
    private function row(array $span): string
    {
        $parts = [
            $this->scalar($span[0] ?? null),
            $this->scalar($span[1] ?? null),
            $this->scalar($span[2] ?? null),
            "'status' => ".$this->scalar($span['status'] ?? null),
            "'rule' => ".$this->scalar($span['rule'] ?? null),
        ];

        return '['.implode(', ', $parts).']';
    }

    private function scalar(mixed $value): string
    {
        return match (true) {
            $value === null => 'null',
            is_int($value) => (string) $value,
            is_string($value) => "'".addcslashes($value, "'\\")."'",
            default => throw new \UnexpectedValueException('The map holds only strings, integers and null.'),
        };
    }
}
