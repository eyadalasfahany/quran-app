<?php

declare(strict_types=1);

use App\Support\QuranText\QuranWordMap;

/*
| ADR 0093: the committed word map (resources/quran/word-map.json, generated by `npm run word-map:api`) holds the same
| 6,236 verses and 77,433 quoted words as the device `words` table. Its counts are what a partial range is checked against.
*/

it('holds 6,236 verses and 77,433 quoted words, in Quran order', function (): void {
    $verses = (new QuranWordMap)->verses();

    expect($verses)->toHaveCount(6236)
        ->and(array_sum(array_map('count', $verses)))->toBe(77433)
        ->and(array_key_first($verses))->toBe('1:1')
        ->and(array_key_last($verses))->toBe('114:6');
});

it('answers the word count and the words of a verse, and nothing for a verse that does not exist', function (): void {
    $map = new QuranWordMap;

    expect($map->wordCount(1, 1))->toBe(4)
        ->and($map->wordCount(2, 181))->toBe(14)
        ->and($map->words(2, 181))->toHaveCount(14)
        ->and($map->wordCount(114, 6))->not->toBeNull()
        ->and($map->wordCount(114, 7))->toBeNull()
        ->and($map->wordCount(115, 1))->toBeNull()
        ->and($map->words(0, 1))->toBeNull();
});

it('keeps the words of a verse as non-empty strings in position order', function (): void {
    $words = (new QuranWordMap)->words(2, 158);

    expect($words)->toBeArray()->toHaveCount(24)
        ->and(array_values(array_filter($words, fn (string $word): bool => $word === '')))->toBe([]);
});
