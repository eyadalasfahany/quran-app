#!/usr/bin/env node
/**
 * Generates `apps/mobile/targets/_shared/Tokens.swift` from `src/colors.ts` (widget + watch palette).
 * Run: node packages/design-tokens/scripts/gen-swift.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { colors } from '../src/colors.ts';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.resolve(__dirname, '../../../apps/mobile/targets/_shared/Tokens.swift');

const widgetKeys = [
  'surface',
  'surfaceRaised',
  'ink',
  'inkMuted',
  'line',
  'fillSecondary',
  'brand',
  'onBrand',
  'brandSurface',
  'onBrandSurface',
  'onBrandSurfaceMuted',
  'goldOnBrandSurface',
  'gold',
  'highlightActive',
];

function hexToComponents(hex) {
  const value = hex.replace('#', '');
  const r = parseInt(value.slice(0, 2), 16) / 255;
  const g = parseInt(value.slice(2, 4), 16) / 255;
  const b = parseInt(value.slice(4, 6), 16) / 255;
  return { r, g, b };
}

function swiftColor(name, hex, indent = '    ') {
  const { r, g, b } = hexToComponents(hex);
  return `${indent}/// design-tokens: ${name}\n${indent}static let ${name} = Color(red: ${r.toFixed(4)}, green: ${g.toFixed(4)}, blue: ${b.toFixed(4)})`;
}

function paletteStruct(mode, theme) {
  const lines = widgetKeys.map((key) => swiftColor(key, theme[key], '        '));
  return `    struct ${mode} {\n${lines.join('\n')}\n    }`;
}

const header = `// Generated by packages/design-tokens/scripts/gen-swift.mjs — do not edit by hand.
import SwiftUI

enum TaybahTokens {
`;

const body = `${paletteStruct('Light', colors.light)}

${paletteStruct('Dark', colors.dark)}
}

extension TaybahTokens {
    static func palette(for colorScheme: ColorScheme) -> (surface: Color, surfaceRaised: Color, ink: Color, inkMuted: Color, line: Color, fillSecondary: Color, brand: Color, onBrand: Color, brandSurface: Color, onBrandSurface: Color, onBrandSurfaceMuted: Color, goldOnBrandSurface: Color, gold: Color, highlightActive: Color) {
        let p = colorScheme == .dark ? Dark.self : Light.self
        return (p.surface, p.surfaceRaised, p.ink, p.inkMuted, p.line, p.fillSecondary, p.brand, p.onBrand, p.brandSurface, p.onBrandSurface, p.onBrandSurfaceMuted, p.goldOnBrandSurface, p.gold, p.highlightActive)
    }
}
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, header + body);

console.log('Wrote', outPath);
