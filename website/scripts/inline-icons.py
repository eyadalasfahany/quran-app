#!/usr/bin/env python3
"""Inline the icon sprite into every website page.

Browsers block external <use href="file.svg#id"> references on file://, and
those references break when the site is served under another path. This copies
every <symbol> from assets/images/icons.svg into an inline sprite right after
each page's <body> tag, and rewrites the external hrefs to "#id".

Idempotent: running it again changes nothing. No dependencies.
Run from anywhere; all paths resolve from this file's location.

    python website/scripts/inline-icons.py
"""

from __future__ import annotations

import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
WEBSITE = REPO / "website"
SPRITE = WEBSITE / "assets" / "images" / "icons.svg"

START = (
    "<!-- icons:start (generated by scripts/inline-icons.py "
    "from assets/images/icons.svg) -->"
)
END = "<!-- icons:end -->"
SVG_OPEN = (
    '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" '
    'focusable="false" '
    'style="position:absolute;width:0;height:0;overflow:hidden">'
)
BLOCK_RE = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
BODY_RE = re.compile(r"<body\b[^>]*>", re.IGNORECASE)
COMMENT_RE = re.compile(r"<!--.*?-->", re.DOTALL)
SYMBOL_RE = re.compile(r"<symbol\b[^>]*>.*?</symbol>", re.DOTALL)
HREF_RE = re.compile(r"/?assets/images/icons\.svg#(?=[A-Za-z0-9_-])")


def read_symbols() -> list[str]:
    # Comments in the sprite contain example <symbol> markup; drop them first.
    text = SPRITE.read_text(encoding="utf-8")
    symbols = SYMBOL_RE.findall(COMMENT_RE.sub("", text))
    if not symbols:
        raise SystemExit(f"no <symbol> elements found in {SPRITE}")
    for symbol in symbols:
        if "--" in symbol:
            raise SystemExit(f"symbol markup contains '--': {symbol[:60]}")
    return symbols


def build_block(symbols: list[str]) -> str:
    return START + SVG_OPEN + "".join(symbols) + "</svg>" + END


def process(path: Path, block: str) -> tuple[int, bool]:
    with open(path, encoding="utf-8", newline="") as handle:
        original = handle.read()

    text, href_count = HREF_RE.subn("#", original)

    if BLOCK_RE.search(text):
        text = BLOCK_RE.sub(lambda _match: block, text, count=1)
    else:
        body = BODY_RE.search(text)
        if body is None:
            raise SystemExit(f"no <body> tag in {path.name}")
        text = text[: body.end()] + block + text[body.end():]

    if text != original:
        with open(path, "w", encoding="utf-8", newline="") as handle:
            handle.write(text)
    return href_count, text != original


def main() -> None:
    symbols = read_symbols()
    block = build_block(symbols)
    for path in sorted(WEBSITE.glob("*.html")):
        href_count, changed = process(path, block)
        status = "changed" if changed else "unchanged"
        print(
            f"{path.name}: {len(symbols)} symbols inlined, "
            f"{href_count} hrefs rewritten ({status})"
        )


if __name__ == "__main__":
    main()
