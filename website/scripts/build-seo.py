#!/usr/bin/env python3
"""Generate SEO head blocks, English pages, JSON-LD and the sitemap.

For every page in PAGES this script:

- rewrites the head of the Arabic source page (website/<slug>.html): the
  language script, and a generated block between seo:start and seo:end markers
  (title, description, robots, canonical, hreflang, Open Graph, Twitter, and
  JSON-LD). Language switch links are pointed at the English and Arabic URLs.
- writes the English copy to website/en/<slug>.html (index becomes en/index.html,
  served at /en). Arabic-only elements are removed, aria labels are switched to
  English, and relative asset and page links are made root-absolute.

It also writes website/sitemap.xml. robots.txt, vercel.json and llms.txt are
hand-written and are not generated here.

Idempotent: running it again changes nothing. No dependencies beyond the
Python standard library. Paths resolve from this file's location.

Run order: after scripts/inline-icons.py, because the English copies start
from the source text that already contains the inlined icon sprite.

    python website/scripts/inline-icons.py
    python website/scripts/build-seo.py
    python website/scripts/build-seo.py --check   # verify outputs, write nothing
"""

from __future__ import annotations

import datetime
import html
import json
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
WEBSITE = REPO / "website"
EN_DIR = WEBSITE / "en"

SITE = "https://taybah-app.com"
PAGES = [  # slug, indexable
    ("index", True), ("features", True), ("sources", True), ("support", True),
    ("privacy", True), ("terms", True), ("delete-account", True), ("suggest", True),
    ("download", False),   # JS redirects mobile UAs (incl. Googlebot smartphone) to the store
    ("qr", False),
    ("404", False),        # no English copy is generated for 404
]

APP_STORE = "https://apps.apple.com/us/app/taybah-quran-prayer-azkar/id6828097265"
PLAY = "https://play.google.com/store/apps/details?id=com.taybahapp.taybah"
EMAIL = "eyadalasfahani@gmail.com"
THEME_COLOR = "#1f4d40"
APPLE_APP = "app-id=6828097265"
OG_IMAGE = SITE + "/assets/images/google-play-feature-graphic.png"
LOGO = SITE + "/assets/images/taybah-logo.png"
APP_SHOTS = WEBSITE / "assets" / "images" / "app"

NAME = {"ar": "طيبة", "en": "Taybah"}
LOCALE = {"ar": "ar_AR", "en": "en_US"}
OTHER = {"ar": "en", "en": "ar"}
HOME_LABEL = {"ar": "الرئيسية", "en": "Home"}
IMAGE_ALT = {"ar": "طيبة: القرآن والصلاة والأذكار", "en": "Taybah: Quran, Prayer & Azkar"}

SEO_START = "<!-- seo:start (generated by scripts/build-seo.py) -->"
SEO_END = "<!-- seo:end -->"
SEO_BLOCK_RE = re.compile(re.escape(SEO_START) + r".*?" + re.escape(SEO_END), re.DOTALL)
TWITTER_END_RE = re.compile(r'<title>.*?<meta name="twitter:card"[^>]*>', re.DOTALL)
TITLE_RE = re.compile(r"<title>(.*?)</title>", re.DOTALL)
DESC_RE = re.compile(r'<meta name="description" content="(.*?)">', re.DOTALL)
HTML_TAG_RE = re.compile(r"<html\b[^>]*>")
LANG_SCRIPT = (
    r"<script>(function(){var d=document.documentElement,"
    r"l=/^\/en(\/|$)/.test(location.pathname)?'en':'ar';"
    r"d.lang=l;d.dir=l==='ar'?'rtl':'ltr';d.classList.add('js')})();</script>"
)
LANG_SCRIPT_RE = re.compile(r"<script>\(function\(\)\{var d=document\.documentElement,.*?</script>", re.DOTALL)
JSON_LD_RE = re.compile(r'<script type="application/ld\+json">(.*?)</script>', re.DOTALL)

VOID = frozenset("area base br col embed hr img input link meta source track wbr".split())
TOKEN_RE = re.compile(
    r"<!--.*?-->"
    r"|<(script|style)\b[^>]*>.*?</\1\s*>"
    r"|<(/?)([a-zA-Z][a-zA-Z0-9-]*)\b([^>]*?)(/?)>",
    re.DOTALL | re.IGNORECASE,
)


class Element:
    """One element: start tag at [start, open_end), whole element ends at end."""

    __slots__ = ("name", "start", "open_end", "end")

    def __init__(self, name: str, start: int, open_end: int, end: int) -> None:
        self.name = name
        self.start = start
        self.open_end = open_end
        self.end = end


def parse_elements(text: str) -> list[Element]:
    """Return every element in document order. Comments are skipped; script and style are opaque."""
    elements: list[Element] = []
    stack: list[Element] = []
    for match in TOKEN_RE.finditer(text):
        token = match.group(0)
        if token.startswith("<!--"):
            continue
        if match.group(1):
            open_end = text.index(">", match.start()) + 1
            elements.append(Element(match.group(1).lower(), match.start(), open_end, match.end()))
            continue
        name = match.group(3).lower()
        if match.group(2) == "/":
            for index in range(len(stack) - 1, -1, -1):
                if stack[index].name == name:
                    for dangling in stack[index + 1:]:
                        dangling.end = match.start()
                        elements.append(dangling)
                    stack[index].end = match.end()
                    elements.append(stack[index])
                    del stack[index:]
                    break
            continue
        if match.group(5) == "/" or name in VOID:
            elements.append(Element(name, match.start(), match.end(), match.end()))
        else:
            stack.append(Element(name, match.start(), match.end(), -1))
    if stack:
        raise SystemExit(f"unclosed <{stack[-1].name}> at offset {stack[-1].start}")
    return sorted(elements, key=lambda element: element.start)


def has_attr(tag: str, name: str, value: str) -> bool:
    return re.search(r'\s' + re.escape(name) + r'="' + re.escape(value) + r'"(?=[\s/>])', tag) is not None


def edit_start_tags(text: str, edit) -> str:
    """Apply edit(element, start_tag) -> start_tag to every start tag."""
    out: list[str] = []
    pos = 0
    for element in parse_elements(text):
        tag = text[element.start:element.open_end]
        new_tag = edit(element, tag)
        if new_tag != tag:
            out.append(text[pos:element.start])
            out.append(new_tag)
            pos = element.open_end
    out.append(text[pos:])
    return "".join(out)


def remove_elements(text: str, predicate) -> str:
    """Remove every element (with its content) whose start tag matches predicate(element, start_tag)."""
    out: list[str] = []
    pos = 0
    for element in parse_elements(text):
        if element.start < pos:
            continue  # nested inside an element already removed
        if predicate(element, text[element.start:element.open_end]):
            out.append(text[pos:element.start])
            pos = element.end
    out.append(text[pos:])
    return "".join(out)


def strip_comments(text: str) -> str:
    """Comments are left untouched by the generator, so checks ignore their content."""
    return re.sub(r"<!--.*?-->", "", text, flags=re.DOTALL)


def esc(value: str) -> str:
    return html.escape(value, quote=True)


def clean_text(fragment: str) -> str:
    return " ".join(html.unescape(re.sub(r"<[^>]+>", "", fragment)).split())


def ar_url(slug: str) -> str:
    return SITE + "/" if slug == "index" else f"{SITE}/{slug}"


def en_url(slug: str) -> str:
    return SITE + "/en" if slug == "index" else f"{SITE}/en/{slug}"


def self_url(slug: str, lang: str) -> str:
    return ar_url(slug) if lang == "ar" else en_url(slug)


def url_path(url: str) -> str:
    return url[len(SITE):]


def git_lastmod(slug: str) -> str:
    result = subprocess.run(
        ["git", "log", "-1", "--format=%cs", "--", f"{slug}.html"],
        cwd=WEBSITE, capture_output=True, text=True, check=False,
    )
    return result.stdout.strip() or datetime.date.today().isoformat()


def read(path: Path) -> str:
    with open(path, encoding="utf-8", newline="") as handle:
        return handle.read()


def write_if_changed(path: Path, text: str) -> bool:
    if path.exists() and read(path) == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(text)
    return True


def read_ar_meta(text: str) -> tuple[str, str]:
    """Arabic title and description: from the generated block if present, else from the source tags."""
    block = SEO_BLOCK_RE.search(text)
    scope = block.group(0) if block else text
    title = TITLE_RE.search(scope)
    desc = DESC_RE.search(scope)
    if title is None or desc is None:
        raise SystemExit("missing <title> or description meta")
    return html.unescape(title.group(1)), html.unescape(desc.group(1))


def read_en_meta(text: str, slug: str) -> tuple[str, str]:
    tag = HTML_TAG_RE.search(text)
    if tag is None:
        raise SystemExit(f"no <html> tag in {slug}.html")
    title = re.search(r'data-title-en="([^"]*)"', tag.group(0))
    desc = re.search(r'data-desc-en="([^"]*)"', tag.group(0))
    if title is None or desc is None:
        raise SystemExit(f"{slug}.html is missing data-title-en or data-desc-en")
    return html.unescape(title.group(1)), html.unescape(desc.group(1))


def extract_faqs(text: str) -> dict[str, list[tuple[str, str]]]:
    """Support FAQ items grouped by the data-l language of the element that contains them."""
    elements = parse_elements(text)
    language_owners = [
        element for element in elements
        if re.search(r'\sdata-l="(ar|en)"', text[element.start:element.open_end])
    ]
    faqs: dict[str, list[tuple[str, str]]] = {"ar": [], "en": []}
    for details in elements:
        tag = text[details.start:details.open_end]
        if details.name != "details" or 'class="faq"' not in tag:
            continue
        owners = [o for o in language_owners if o.start <= details.start and o.end >= details.end]
        if not owners:
            raise SystemExit("FAQ item is not inside a data-l container")
        owner = max(owners, key=lambda o: o.start)
        lang = re.search(r'data-l="(ar|en)"', text[owner.start:owner.open_end]).group(1)
        inner = text[details.start:details.end]
        summary = re.search(r"<summary>(.*?)</summary>", inner, re.DOTALL)
        question = re.search(r"<h3>(.*?)</h3>", summary.group(1), re.DOTALL)
        answer = re.search(r"<p>(.*?)</p>", inner[summary.end():], re.DOTALL)
        if question is None or answer is None:
            raise SystemExit("FAQ item is missing its h3 question or p answer")
        faqs[lang].append((clean_text(question.group(1)), clean_text(answer.group(1))))
    for lang in ("ar", "en"):
        if len(faqs[lang]) != 5:
            raise SystemExit(f"expected 5 FAQ items for {lang}, found {len(faqs[lang])}")
    return faqs


def faq_entity(slug: str, lang: str, faqs: list[tuple[str, str]]) -> dict:
    return {
        "@type": "FAQPage",
        "@id": self_url(slug, lang) + "#faq",
        "mainEntity": [
            {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}}
            for q, a in faqs
        ],
    }


def json_ld(slug: str, lang: str, title: str, desc: str, faqs: list[tuple[str, str]] | None) -> str:
    other = OTHER[lang]
    self_u = self_url(slug, lang)
    graph: list[dict] = [{
        "@type": "WebPage",
        "@id": self_u + "#webpage",
        "url": self_u,
        "name": title,
        "description": desc,
        "inLanguage": lang,
        "isPartOf": {"@id": SITE + "/#website"},
        "about": {"@id": SITE + "/#app"},
    }]
    if slug != "index":
        graph.append({
            "@type": "BreadcrumbList",
            "itemListElement": [
                {"@type": "ListItem", "position": 1, "name": HOME_LABEL[lang], "item": self_url("index", lang)},
                {"@type": "ListItem", "position": 2, "name": title, "item": self_u},
            ],
        })
    if faqs is not None:
        graph.append(faq_entity(slug, lang, faqs))
    if slug == "index":
        graph.append({
            "@type": "WebSite",
            "@id": SITE + "/#website",
            "url": SITE + "/",
            "name": NAME[lang],
            "alternateName": NAME[other],
            "inLanguage": ["ar", "en"],
            "publisher": {"@id": SITE + "/#organization"},
        })
        graph.append({
            "@type": "Organization",
            "@id": SITE + "/#organization",
            "name": "Taybah",
            "alternateName": "طيبة",
            "url": SITE + "/",
            "logo": {"@type": "ImageObject", "url": LOGO, "width": 1254, "height": 1254},
            "email": EMAIL,
            "sameAs": [APP_STORE, PLAY],
        })
        screenshots = sorted(
            SITE + "/assets/images/app/" + path.name
            for path in APP_SHOTS.glob(f"{lang}-0*.webp")
            if "-ipad-" not in path.name and "-watch-" not in path.name
        )
        graph.append({
            "@type": "MobileApplication",
            "@id": SITE + "/#app",
            "name": NAME[lang],
            "alternateName": NAME[other],
            "description": desc,
            "url": self_u,
            "operatingSystem": "iOS, iPadOS, watchOS, Android",
            "applicationCategory": "ReferenceApplication",
            "inLanguage": ["ar", "en"],
            "isAccessibleForFree": True,
            "offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD"},
            "installUrl": [APP_STORE, PLAY],
            "sameAs": [APP_STORE, PLAY],
            "publisher": {"@id": SITE + "/#organization"},
            "image": LOGO,
            "screenshot": screenshots,
        })
    payload = {"@context": "https://schema.org", "@graph": graph}
    text = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    if "<!--" in text:
        raise SystemExit(f"JSON-LD for {slug} ({lang}) contains an HTML comment opener")
    return text


def seo_block(slug: str, lang: str, title: str, desc: str, indexable: bool,
              faqs: list[tuple[str, str]] | None) -> str:
    is_404 = slug == "404"
    other = OTHER[lang]
    self_u = self_url(slug, lang)
    lines = [
        SEO_START,
        f"<title>{esc(title)}</title>",
        f'<meta name="description" content="{esc(desc)}">',
    ]
    if not indexable:
        lines.append('<meta name="robots" content="noindex">')
    lines += [
        f'<meta name="theme-color" content="{THEME_COLOR}">',
        f'<meta name="apple-itunes-app" content="{APPLE_APP}">',
    ]
    if not is_404:
        lines += [
            f'<link rel="canonical" href="{self_u}">',
            f'<link rel="alternate" hreflang="ar" href="{ar_url(slug)}">',
            f'<link rel="alternate" hreflang="en" href="{en_url(slug)}">',
            f'<link rel="alternate" hreflang="x-default" href="{ar_url(slug)}">',
        ]
    lines += [
        f'<meta property="og:site_name" content="{esc(NAME[lang])}">',
        f'<meta property="og:locale" content="{LOCALE[lang]}">',
        f'<meta property="og:locale:alternate" content="{LOCALE[other]}">',
        '<meta property="og:type" content="website">',
    ]
    if not is_404:
        lines.append(f'<meta property="og:url" content="{self_u}">')
    lines += [
        f'<meta property="og:title" content="{esc(title)}">',
        f'<meta property="og:description" content="{esc(desc)}">',
        f'<meta property="og:image" content="{OG_IMAGE}">',
        f'<meta property="og:image:secure_url" content="{OG_IMAGE}">',
        '<meta property="og:image:type" content="image/png">',
        '<meta property="og:image:width" content="1024">',
        '<meta property="og:image:height" content="500">',
        f'<meta property="og:image:alt" content="{esc(IMAGE_ALT[lang])}">',
        '<meta name="twitter:card" content="summary_large_image">',
    ]
    if not is_404:
        lines.append(f'<script type="application/ld+json">{json_ld(slug, lang, title, desc, faqs)}</script>')
    lines.append(SEO_END)
    return "\n".join(lines)


def replace_seo_block(text: str, block: str) -> str:
    if SEO_BLOCK_RE.search(text):
        new_text, count = SEO_BLOCK_RE.subn(lambda _match: block, text, count=1)
    else:
        if text.count("<title>") != 1:
            raise SystemExit("expected exactly one <title> in source")
        new_text, count = TWITTER_END_RE.subn(lambda _match: block, text, count=1)
    if count != 1:
        raise SystemExit("could not place the SEO block")
    return new_text


def set_switch_links(text: str, slug: str) -> str:
    """Point the header language switch at the English and Arabic URLs of this page."""
    home = slug in ("index", "404")
    en_path = "/en" if home else f"/en/{slug}"
    ar_path = "/" if home else f"/{slug}"
    counts = {"en": 0, "ar": 0}

    def edit(element, tag: str) -> str:
        if element.name != "a":
            return tag
        if has_attr(tag, "data-l", "ar") and re.search(r'\shref="(\?lang=en|/en(/[^"]*)?)"', tag):
            counts["en"] += 1
            return re.sub(r'\shref="[^"]*"', lambda _m: f' href="{en_path}"', tag, count=1)
        if has_attr(tag, "data-l", "en") and re.search(r'\shref="(\?lang=ar|/[^"]*)"', tag):
            counts["ar"] += 1
            return re.sub(r'\shref="[^"]*"', lambda _m: f' href="{ar_path}"', tag, count=1)
        return tag

    new_text = edit_start_tags(text, edit)
    if counts != {"en": 1, "ar": 1}:
        raise SystemExit(f"{slug}.html: expected one English and one Arabic switch link, got {counts}")
    return new_text


def aria_edit(_element, tag: str) -> str:
    match = re.search(r'\sdata-aria-en="([^"]*)"', tag)
    if match is None:
        return tag
    label = match.group(1)
    if re.search(r'\saria-label="[^"]*"', tag):
        return re.sub(r'\saria-label="[^"]*"', lambda _m: f' aria-label="{label}"', tag, count=1)
    return re.sub(
        r"^<[a-zA-Z][a-zA-Z0-9-]*",
        lambda m: m.group(0) + f' aria-label="{label}"',
        tag,
        count=1,
    )


def rewrite_links(text: str) -> str:
    text = re.sub(r'(href|src)="assets/', lambda m: f'{m.group(1)}="/assets/', text)
    slugs = "|".join(re.escape(slug) for slug, _ in PAGES)

    def page_link(match: re.Match) -> str:
        slug, fragment = match.group(1), match.group(2) or ""
        if slug == "index":
            return f'href="/en{fragment}"'
        return f'href="/en/{slug}{fragment}"'

    return re.sub(r'href="(' + slugs + r')\.html(#[^"]*)?"', page_link, text)


def build_english(slug: str, source: str, en_block: str) -> str:
    text, count = re.subn(r'<html lang="ar" dir="rtl"', '<html lang="en" dir="ltr"', source, count=1)
    if count != 1:
        raise SystemExit(f"{slug}.html: no '<html lang=\"ar\" dir=\"rtl\"' tag")
    text = replace_seo_block(text, en_block)
    text = remove_elements(text, lambda _e, tag: has_attr(tag, "data-l", "ar"))
    text = edit_start_tags(text, aria_edit)
    text = rewrite_links(text)
    marker = "<!DOCTYPE html>\n"
    if not text.startswith(marker):
        raise SystemExit(f"{slug}.html does not start with '<!DOCTYPE html>' on its own line")
    return (
        marker
        + f"<!-- Generated by scripts/build-seo.py from ../{slug}.html. Do not edit. -->\n"
        + text[len(marker):]
    )


def build_sitemap() -> str:
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" '
        'xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    ]
    for slug, indexable in PAGES:
        if not indexable:
            continue
        lastmod = git_lastmod(slug)
        ar, en = ar_url(slug), en_url(slug)
        for loc in (ar, en):
            lines += [
                "  <url>",
                f"    <loc>{loc}</loc>",
                f"    <lastmod>{lastmod}</lastmod>",
                f'    <xhtml:link rel="alternate" hreflang="ar" href="{ar}"/>',
                f'    <xhtml:link rel="alternate" hreflang="en" href="{en}"/>',
                f'    <xhtml:link rel="alternate" hreflang="x-default" href="{ar}"/>',
                "  </url>",
            ]
    lines.append("</urlset>")
    return "\n".join(lines) + "\n"


def generate() -> None:
    sources: dict[Path, str] = {}
    english: dict[Path, str] = {}
    for slug, indexable in PAGES:
        source_path = WEBSITE / f"{slug}.html"
        original = read(source_path)
        if original.count("<title>") != 1:
            raise SystemExit(f"{source_path.name} must contain exactly one <title>")

        ar_title, ar_desc = read_ar_meta(original)
        en_title, en_desc = read_en_meta(original, slug)
        faqs = extract_faqs(original) if slug == "support" else {"ar": None, "en": None}

        ar_block = seo_block(slug, "ar", ar_title, ar_desc, indexable, faqs["ar"])
        source = LANG_SCRIPT_RE.sub(lambda _m: LANG_SCRIPT, original, count=1)
        source = replace_seo_block(source, ar_block)
        source = set_switch_links(source, slug)
        sources[source_path] = source

        if slug != "404":
            en_block = seo_block(slug, "en", en_title, en_desc, indexable, faqs["en"])
            text = build_english(slug, source, en_block)
            if 'data-l="ar"' in strip_comments(text):
                raise SystemExit(f"{slug}.html: English copy still contains data-l=\"ar\"")
            english[EN_DIR / f"{slug}.html"] = text

    if len(english) != 10:
        raise SystemExit(f"expected 10 English pages, built {len(english)}")

    sitemap = build_sitemap()

    for path, text in sources.items():
        status = "changed" if write_if_changed(path, text) else "unchanged"
        print(f"{path.relative_to(WEBSITE)}: {status}")
    for path, text in english.items():
        status = "changed" if write_if_changed(path, text) else "unchanged"
        print(f"{path.relative_to(WEBSITE)}: {status}")
    status = "changed" if write_if_changed(WEBSITE / "sitemap.xml", sitemap) else "unchanged"
    print(f"sitemap.xml: {status}")


def file_for_url(loc: str) -> Path:
    path = url_path(loc)
    if path in ("", "/"):
        return WEBSITE / "index.html"
    if path == "/en":
        return EN_DIR / "index.html"
    if path.startswith("/en/"):
        return EN_DIR / (path[len("/en/"):] + ".html")
    return WEBSITE / (path[1:] + ".html")


def first_match(pattern: str, text: str) -> str | None:
    match = re.search(pattern, text)
    return html.unescape(match.group(1)) if match else None


def check() -> None:
    errors: list[str] = []
    pages = [WEBSITE / f"{slug}.html" for slug, _ in PAGES]
    pages += [EN_DIR / f"{slug}.html" for slug, _ in PAGES if slug != "404"]
    if len(pages) != 21:
        errors.append(f"expected 21 pages, found {len(pages)}")
    for path in pages:
        if not path.exists():
            errors.append(f"missing {path.relative_to(WEBSITE)}")
            continue
        text = read(path)
        rel = path.relative_to(WEBSITE)
        blocks = JSON_LD_RE.findall(text)
        expected = 0 if path.stem == "404" else 1
        if len(blocks) != expected:
            errors.append(f"{rel}: expected {expected} JSON-LD block(s), found {len(blocks)}")
        for block in blocks:
            try:
                json.loads(block)
            except ValueError as exc:
                errors.append(f"{rel}: JSON-LD does not parse: {exc}")
        canonical = first_match(r'<link rel="canonical" href="([^"]*)">', text)
        og_url = first_match(r'<meta property="og:url" content="([^"]*)">', text)
        if canonical != og_url:
            errors.append(f"{rel}: og:url {og_url!r} != canonical {canonical!r}")
        if path.stem == "404" and (canonical is not None or 'noindex' not in text):
            errors.append(f"{rel}: 404 must be noindex with no canonical")
        if path.parent == EN_DIR:
            if 'data-l="ar"' in strip_comments(text):
                errors.append(f"{rel}: contains data-l=\"ar\" outside comments")
            if re.search(r'(href|src)="assets/', text):
                errors.append(f"{rel}: contains a relative assets/ URL")
            if '<html lang="en" dir="ltr"' not in text:
                errors.append(f"{rel}: html is not lang=en dir=ltr")

    sitemap_path = WEBSITE / "sitemap.xml"
    try:
        root = ET.parse(sitemap_path).getroot()
    except ET.ParseError as exc:
        errors.append(f"sitemap.xml does not parse: {exc}")
        root = None
    if root is not None:
        ns = "{http://www.sitemaps.org/schemas/sitemap/0.9}"
        locs = [node.text for node in root.iter(ns + "loc")]
        if len(locs) != 16:
            errors.append(f"sitemap: expected 16 <loc> entries, found {len(locs)}")
        for loc in locs:
            target = file_for_url(loc)
            if not target.exists():
                errors.append(f"sitemap: {loc} maps to missing {target.relative_to(WEBSITE)}")
                continue
            canonical = first_match(r'<link rel="canonical" href="([^"]*)">', read(target))
            if canonical != loc:
                errors.append(f"sitemap: {loc} != canonical {canonical!r} of {target.relative_to(WEBSITE)}")

    if errors:
        for error in errors:
            print(error)
        raise SystemExit(f"{len(errors)} check(s) failed")
    print(f"checks passed: {len(pages)} pages, JSON-LD parsed, sitemap canonicals match, og:url matches canonical")


def main() -> None:
    # A new page that isn't in PAGES would ship with no English copy, sitemap entry or SEO head.
    missing = sorted({p.stem for p in WEBSITE.glob("*.html")} - {slug for slug, _ in PAGES})
    if missing:
        raise SystemExit(f"Add these pages to PAGES in scripts/build-seo.py: {', '.join(missing)}")
    if "--check" in sys.argv[1:]:
        check()
    else:
        generate()


if __name__ == "__main__":
    main()
